export function formatLocalDate(value = new Date()) {
  const date = value instanceof Date ? value : new Date(value)
  const year = date.getFullYear()
  const month = String(date.getMonth() + 1).padStart(2, '0')
  const day = String(date.getDate()).padStart(2, '0')
  return `${year}-${month}-${day}`
}

/**
 * Devuelve la fecha y hora LOCAL actual (o del valor dado) en formato
 * "YYYY-MM-DDTHH:MM" para usar en inputs type="datetime-local".
 * No usa getTimezoneOffset() — trabaja directamente con los componentes
 * locales del Date, respetando la TZ del VPS/servidor (UTC-3).
 */
export function localDateTimeString(value = new Date()) {
  const date = value instanceof Date ? value : new Date(value)
  const year = date.getFullYear()
  const month = String(date.getMonth() + 1).padStart(2, '0')
  const day = String(date.getDate()).padStart(2, '0')
  const hours = String(date.getHours()).padStart(2, '0')
  const minutes = String(date.getMinutes()).padStart(2, '0')
  return `${year}-${month}-${day}T${hours}:${minutes}`
}

